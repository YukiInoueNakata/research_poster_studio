// Generate THIRD_PARTY_NOTICES.md (node scripts/third-party-notices.mjs).
//
// Lists every third-party package shipped in the desktop app and the CLI —
// production npm dependencies of the published workspaces and the Rust crates
// of the Tauri app — with its license and the license / notice texts found in
// the package. Identical texts are printed once and referenced by number.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright)([-_.].*)?$/i;
const shell = process.platform === "win32";

/** @type {Map<string, {name:string, version:string, license:string, repo:string, dir:string, kind:string}>} */
const pkgs = new Map();

// ---- npm: production dependency tree of the shipped workspaces ----
const npmTree = JSON.parse(
  execFileSync("npm", ["ls", "--omit=dev", "--all", "--json", "--long", "-w", "@rps/desktop-app", "-w", "@rps/cli"], {
    cwd: ROOT, encoding: "utf8", shell, maxBuffer: 256 * 1024 * 1024,
  }),
);
const walkNpm = (deps) => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (!d || !d.version) continue;
    if (name.startsWith("@rps/")) { walkNpm(d.dependencies); continue; }
    const key = `npm:${name}@${d.version}`;
    if (!pkgs.has(key)) {
      const dir = d.path ?? path.join(ROOT, "node_modules", name);
      let license = "";
      let repo = "";
      try {
        const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
        license = typeof pj.license === "string" ? pj.license : pj.license?.type ?? (pj.licenses ?? []).map((l) => l.type ?? l).join(" OR ");
        repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url ?? pj.homepage ?? "";
      } catch {}
      pkgs.set(key, { name, version: d.version, license: license || "UNKNOWN", repo, dir, kind: "npm" });
    }
    walkNpm(d.dependencies);
  }
};
walkNpm(npmTree.dependencies);

// ---- Rust: resolved crates of the Tauri app (all targets) ----
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: path.join(ROOT, "packages", "desktop-app", "src-tauri"), encoding: "utf8", maxBuffer: 512 * 1024 * 1024,
  }),
);
const resolved = new Set(meta.resolve.nodes.map((n) => n.id));
const members = new Set(meta.workspace_members);
for (const p of meta.packages) {
  if (!resolved.has(p.id) || members.has(p.id)) continue;
  pkgs.set(`cargo:${p.name}@${p.version}`, {
    name: p.name, version: p.version, license: p.license ?? (p.license_file ? `see ${p.license_file}` : "UNKNOWN"),
    repo: p.repository ?? "", dir: path.dirname(p.manifest_path), kind: "cargo",
  });
}

// ---- collect texts (deduplicated) ----
const texts = new Map(); // text -> index
const rows = [];
for (const p of [...pkgs.values()].sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name))) {
  const refs = [];
  let files = [];
  try { files = fs.readdirSync(p.dir).filter((f) => LICENSE_FILE.test(f)).sort(); } catch {}
  for (const f of files) {
    let t;
    try { t = fs.readFileSync(path.join(p.dir, f), "utf8").replace(/\r\n/g, "\n").trim(); } catch { continue; }
    if (!t) continue;
    if (!texts.has(t)) texts.set(t, texts.size + 1);
    refs.push(`[T${texts.get(t)}](#t${texts.get(t)})`);
  }
  rows.push(`| ${p.kind} | ${p.name} | ${p.version} | ${p.license.replace(/\|/g, "/")} | ${refs.join(" ") || "—"} |`);
}

const missing = rows.filter((r) => r.endsWith("| — |")).length;
const md = [
  "# Third-party notices",
  "",
  "Research Poster Studio (Apache-2.0, see `LICENSE` and `NOTICE`) ships the following third-party",
  "software. Each package keeps its own license; the license and notice texts found in the packages",
  "are reproduced below (identical texts are shown once). Generated by",
  "`node scripts/third-party-notices.mjs`; do not edit by hand.",
  "",
  `Packages: ${rows.length} (npm ${[...pkgs.values()].filter((p) => p.kind === "npm").length}, Rust ${[...pkgs.values()].filter((p) => p.kind === "cargo").length}). Without a bundled license file: ${missing} (see the package's repository for its license text).`,
  "",
  "## Embedded components",
  "",
  "- `@viz-js/viz` (MIT) embeds **Graphviz 15.0.0** compiled to WebAssembly. Graphviz is licensed under the",
  "  Eclipse Public License 2.0 (https://graphviz.org/license/, checked 2026-10-03); its source code is available",
  "  at https://gitlab.com/graphviz/graphviz.",
  "",
  "## Packages",
  "",
  "| Source | Package | Version | License | Texts |",
  "|---|---|---|---|---|",
  ...rows,
  "",
  "## License and notice texts",
  "",
  ...[...texts.entries()].flatMap(([t, i]) => [`### T${i}`, "", "```text", t.replace(/```/g, "'''"), "```", ""]),
].join("\n");
fs.writeFileSync(OUT, md, "utf8");
console.log(`wrote ${path.relative(ROOT, OUT)}: ${rows.length} packages, ${texts.size} distinct texts, ${missing} without a license file, ${(md.length / 1024).toFixed(0)} KB`);
